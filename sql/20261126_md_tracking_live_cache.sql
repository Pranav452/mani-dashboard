-- Track & Trace live-status cache. Dashboard-owned table; the only table this app writes to.
-- Idempotent; compatible with older SQL Server compatibility levels.
IF OBJECT_ID('dbo.MD_TRACKING_LIVE_CACHE', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.MD_TRACKING_LIVE_CACHE (
    NUMBER      NVARCHAR(20)  NOT NULL CONSTRAINT PK_MD_TRACKING_LIVE_CACHE PRIMARY KEY,
    CARRIER     NVARCHAR(100) NULL,
    STATUS      NVARCHAR(100) NULL,
    LIVE_ETA    DATETIME      NULL,
    ETA_CHANGED BIT           NOT NULL CONSTRAINT DF_MD_TLC_ETA_CHANGED DEFAULT 0,
    SUMMARY     NVARCHAR(MAX) NULL,
    SOURCE      NVARCHAR(50)  NULL,
    OK          BIT           NOT NULL CONSTRAINT DF_MD_TLC_OK DEFAULT 0,
    CHECKED_AT  DATETIME      NOT NULL CONSTRAINT DF_MD_TLC_CHECKED_AT DEFAULT GETUTCDATE(),
    RAW         NVARCHAR(MAX) NULL
  )
END
